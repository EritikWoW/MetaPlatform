# ----------------- runtime state -----------------
_lang: str = "en"
_inited = False

# observers: entries with optional widget weakref (auto-remove on destroy)
_observers: list[dict[str, Any]] = []


def init_i18n(default_lang: str = "en") -> None:
    """Load language once for the whole program (from settings.json)."""
    global _inited, _lang
    if _inited:
        return
    data = _load_settings()
    lang = str(data.get("lang") or default_lang)
    if lang not in SUPPORTED:
        lang = "en"
    _lang = lang
    _inited = True


def get_lang() -> str:
    return _lang


def set_lang(lang: str) -> None:
    global _lang
    if lang not in SUPPORTED:
        lang = "en"
    if _lang == lang:
        return

    _lang = lang

    # persist
    data = _load_settings()
    data["lang"] = _lang
    _save_settings(data)

    # notify
    _notify()

# ----------------- extra translations -----------------
# Keep large/fast-growing UI dictionaries in a separate module to avoid
# bloating this file and to make regeneration simpler.
try:
    from src.ui_qt.i18n_extra import EXTRA_TR as _EXTRA_TR

    for _lang_code, _tbl in (_EXTRA_TR or {}).items():
        if not isinstance(_tbl, dict):
            continue
        _TR.setdefault(str(_lang_code), {}).update({str(k): str(v) for k, v in _tbl.items()})
except Exception:
    # Never break startup due to a translation module issue.
    pass



def t(key: str, **kwargs: Any) -> str:
    table = _TR.get(_lang) or _TR["en"]
    s = table.get(key) or _TR["en"].get(key) or key
    if kwargs:
        try:
            return s.format(**kwargs)
        except Exception:
            return s
    return s


def bind(callback: Callable[[], None], widget: Optional[object] = None) -> None:
    """
    Bind callback to language changes.
    If widget is provided (QObject), callback auto-unbinds when widget is destroyed.
    """
    entry: dict[str, Any] = {"cb": callback, "wref": None}

    if widget is not None:
        # weakref для защиты от утечек
        entry["wref"] = weakref.ref(widget)

        # PySide6 / Qt: у QObject есть сигнал destroyed
        try:
            destroyed = getattr(widget, "destroyed", None)
            if destroyed is not None:
                def _on_destroyed(*_args: Any) -> None:
                    try:
                        _observers.remove(entry)
                    except ValueError:
                        pass

                destroyed.connect(_on_destroyed)  # type: ignore[attr-defined]
        except Exception:
            pass

    _observers.append(entry)


def _notify() -> None:
    dead: list[dict[str, Any]] = []
    for entry in list(_observers):
        wref = entry.get("wref")
        if wref is not None and wref() is None:
            dead.append(entry)
            continue
        cb = entry.get("cb")
        try:
            cb()
        except Exception:
            # не ломаем программу из-за одного слушателя
            pass

    for d in dead:
        try:
            _observers.remove(d)
        except ValueError:
            pass
